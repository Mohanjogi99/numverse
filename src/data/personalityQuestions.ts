export function getQuestionsForTier(tier: PersonalityTier): PersonalityQuestion[] {
  const normTier = tier === 'quick' ? 'free' : tier === 'deep' ? 'complete' : tier;
  if (normTier === 'free') {
    return PERSONALITY_QUESTIONS.slice(0, 10);
  }
  if (normTier === 'standard') {
    return PERSONALITY_QUESTIONS.slice(0, 25);
  }
  return PERSONALITY_QUESTIONS; // complete (50 questions)
}
